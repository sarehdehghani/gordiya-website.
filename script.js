/* ---------- Custom cursor + magnetic buttons ---------- */
if (matchMedia('(pointer:fine)').matches) {
  root.classList.add('has-cursor');
  const dot = document.querySelector('.cur-dot'), ring = document.querySelector('.cur-ring');
  let mx = innerWidth / 2, my = innerHeight / 2, rx = mx, ry = my;
  addEventListener('mousemove', e => { mx = e.clientX; my = e.clientY; dot.style.transform = `translate(${mx}px,${my}px)`; });
  (function follow(){
    rx += (mx - rx) * .16; ry += (my - ry) * .16;
    ring.style.transform = `translate(${rx}px,${ry}px)`;
    requestAnimationFrame(follow);
  })();
  document.addEventListener('mouseover', e => {
    ring.classList.toggle('big', !!e.target.closest('a,button,.svc,.work,.idea-row,input,select,textarea,.giant'));
  });
  document.querySelectorAll('.mag').forEach(b => {
    b.addEventListener('mousemove', e => {
      const r = b.getBoundingClientRect();
      const x = e.clientX - (r.left + r.width / 2), y = e.clientY - (r.top + r.height / 2);
      b.style.transform = `translate(${x * .25}px,${y * .4}px)`;
    });
    b.addEventListener('mouseleave', () => b.style.transform = '');
  });
}

