/* ---------- Word-by-word split (word-level so Persian letters stay joined) ---------- */
function split(el){
  const words = el.textContent.trim().split(/\s+/);
  el.innerHTML = words.map((w, i) => `<span class="w"><span style="--i:${i}">${w}</span></span>`).join(' ');
  if (el.classList.contains('in')) {
    el.classList.remove('in');
    requestAnimationFrame(() => requestAnimationFrame(() => el.classList.add('in')));
  }
}

function applyLang(l){
  lang = l;
  root.lang = l; root.dir = l === 'fa' ? 'rtl' : 'ltr';
  document.getElementById('bs-rtl').disabled = l !== 'fa';
  document.getElementById('bs-ltr').disabled = l === 'fa';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = T[l][el.dataset.i18n]; if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = T[l][el.dataset.i18nPh] || ''; });
  document.querySelectorAll('[data-split]').forEach(split);
  document.getElementById('langBtn').textContent = l === 'fa' ? 'EN' : 'فا';
  localStorage.setItem('g-lang', l);
}
function applyTheme(t){
  theme = t; root.dataset.theme = t; root.dataset.bsTheme = t;
  localStorage.setItem('g-theme', t);
}
applyTheme(theme); applyLang(lang);
document.getElementById('langBtn').onclick = () => applyLang(lang === 'fa' ? 'en' : 'fa');
document.getElementById('themeBtn').onclick = () => applyTheme(theme === 'dark' ? 'light' : 'dark');

/* ---------- Reveal + counters (start after loader) ---------- */
const io = new IntersectionObserver(es => es.forEach(e => {
  if (!e.isIntersecting) return;
  e.target.classList.add('in');
  e.target.querySelectorAll('[data-count]').forEach(c => { if (!c.dataset.done) { c.dataset.done = 1; count(c); } });
  io.unobserve(e.target);
}), { threshold: .15 });

function count(el){
  const to = +el.dataset.count; let n = 0;
  const step = Math.max(1, Math.ceil(to / 70));
  const t = setInterval(() => {
    n += step; if (n >= to) { n = to; clearInterval(t); }
    el.textContent = n + '+';
  }, 22);
}

